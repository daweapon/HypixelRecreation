        out.append("      \"name\": \"").append(room.name()).append("\",\n");
        out.append("      \"shape\": \"").append(result.shape()).append("\",\n");
        out.append("      \"kind\": \"").append(room.kind()).append("\",\n");
        out.append("      \"secretCount\": ").append(result.secretCount()).append(",\n");
        out.append("      \"tags\": [\"").append(room.tag()).append("\", \"").append(room.kind().toLowerCase(Locale.ROOT)).append("\"],\n");
        if (room.catalogueName() != null) out.append("      \"catalogueName\": \"").append(room.catalogueName()).append("\",\n");
        if (room.annexMinZ() != RoomSource.NO_ANNEX) out.append("      \"fixedRotation\": \"DEG_180\",\n");
        out.append("      \"structure\": {\"file\": \"").append(room.folder()).append('/').append(room.id()).append(".schem\", \"x\": ").append(result.structureX())
                .append(", \"y\": ").append(result.structureY()).append(", \"z\": ").append(result.structureZ()).append("},\n");
