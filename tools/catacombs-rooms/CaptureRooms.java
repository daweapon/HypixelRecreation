/**
 * Rooms cut from captured Hypixel Catacombs runs (clientmod full captures, world_002 of each). Every cell of the grid is
 * named by the community room catalogue, which also supplies the room's secrets, route points and crypt count; doors
 * are read from the blocks in the seams between rooms. Sightings of one room that differ in their blocks are kept as
 * variants. A captured room that the M7 practice map also has replaces the practice-map template under the same id and
 * in the same frame.
 */
