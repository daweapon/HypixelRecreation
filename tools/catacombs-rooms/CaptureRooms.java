    record Run(String id, boolean floorOne, AnvilWorld world, List<Seen> rooms, List<int[][]> doors, Map<String, String> placed,
               List<CaptureMobs.Mob> mobs, double[] entry) {
        Seen roomAt(int gx, int gz) {
            for (Seen room : rooms) for (int[] cell : room.cells()) if (cell[0] == gx && cell[1] == gz) return room;
            return null;
        }
    }

    record Seen(Run run, int[][] cells, RoomCatalogue.Found found) {
        String name() {
            return found.entry().name();
        }

        List<CaptureMobs.Mob> mobs() {
            List<CaptureMobs.Mob> inside = new ArrayList<>();
            for (CaptureMobs.Mob mob : run.mobs()) {
                if (run.roomAt(Math.floorDiv((int) Math.floor(mob.x()) - ORIGIN, 32), Math.floorDiv((int) Math.floor(mob.z()) - ORIGIN, 32)) == this) {
                    inside.add(mob);
                }
            }
            return inside;
        }

        boolean blind() {
            List<CaptureMobs.Mob> normal = mobs().stream().filter(mob -> !MINIBOSSES.contains(mob.mobId())).toList();
            return !normal.isEmpty() && normal.stream().noneMatch(CaptureMobs.Mob::starred);
        }
    }

    record Reference(String id, CaptureRooms.SchemBlocks blocks, int structureX, int structureY, int structureZ) {
    }

    static void extract(List<Path> captures, RoomCatalogue catalogue, Path out) throws IOException {
        List<Run> runs = new ArrayList<>();
        for (Path capture : captures) runs.add(load(capture, catalogue));
        Map<String, Reference> references = references(out);
        Map<String, Double> starRatio = starRatios(runs);

        Map<String, List<List<Seen>>> variants = new LinkedHashMap<>();
        for (Run run : runs) {
            for (Seen seen : run.rooms()) {
                List<List<Seen>> clusters = variants.computeIfAbsent(seen.name(), ignored -> new ArrayList<>());
                List<Seen> home = null;
                for (List<Seen> cluster : clusters) {
                    if (difference(cluster.getFirst(), seen) < VARIANT_GAP) {
                        home = cluster;
                        break;
                    }
                }
                if (home == null) clusters.add(home = new ArrayList<>());
                home.add(seen);
            }
        }

        Map<String, ExtractRooms.Result> byId = new LinkedHashMap<>();
        Set<String> replaced = new LinkedHashSet<>();
        for (Map.Entry<String, List<List<Seen>>> entry : variants.entrySet()) {
            String name = entry.getKey();
            String m7Id = M7_IDS.get(name);
            Reference reference = m7Id == null ? null : references.get(m7Id);
            List<ExtractRooms.Result> built = new ArrayList<>();
            List<Double> gaps = new ArrayList<>();
            for (List<Seen> cluster : entry.getValue()) {
                Seen chosen = choose(cluster);
                RoomSource.Room room = room(chosen, cluster, catalogue, starRatio);
                List<Seen> sources = new ArrayList<>(cluster);
                entry.getValue().stream().filter(other -> other != cluster).forEach(sources::addAll);
                DoorPieces.Closed closed = DoorPieces.closeOwnDoors(chosen, sources);
                ExtractRooms.Result best = null;
                double bestGap = 1;
                for (int turns : reference == null ? new int[]{0} : validTurns(room)) {
                    ExtractRooms.Result result = ExtractRooms.extract(chosen.run().world(), room.withTurns(turns), grid(chosen, cluster), closed.walls(),
                            ExtractRooms.Closing.HOLES);
                    double gap = reference == null ? 1 : gap(result, reference);
                    if (best == null || gap < bestGap) {
                        best = result;
                        bestGap = gap;
                    }
                }
                chosen.run().world().override(closed.states());
                best = best.withBox(ExtractRooms.extract(chosen.run().world(), best.room(), grid(chosen, cluster), closed.walls(),
                        ExtractRooms.Closing.NONE).box());
                chosen.run().world().clearOverrides();
                built.add(best);
                gaps.add(bestGap);
            }
            int replacing = -1;
            for (int i = 0; i < built.size(); i++) {
                if (gaps.get(i) < REPLACE_GAP && (replacing < 0 || gaps.get(i) < gaps.get(replacing))) replacing = i;
            }
            for (int i = 0; i < built.size(); i++) {
                ExtractRooms.Result result = built.get(i);
                String base = result.room().id();
                String id = i == replacing ? m7Id : base;
                for (int n = 2; byId.containsKey(id) || (i != replacing && id.equals(m7Id)); n++) id = base + "_" + n;
                if (i == replacing) replaced.add(m7Id);
                ExtractRooms.Result renamed = rename(result, id);
                byId.put(id, renamed);
                System.out.println(name + " variant " + (i + 1) + " -> " + id + (reference != null ? String.format(Locale.ROOT, " (%.3f from %s)", gaps.get(i), m7Id) : "")
                        + " from " + chosenLabel(entry.getValue().get(i)));
            }
        }

        List<ExtractRooms.Result> floorOne = new ArrayList<>();
        List<ExtractRooms.Result> masterSeven = new ArrayList<>();
        for (ExtractRooms.Result result : byId.values()) {
            boolean f1 = result.room().tag().equals("hypixel_f1");
            Files.createDirectories(out.resolve(FOLDER));
            byte[] bytes = ExtractRooms.schematic(result.box());
            Files.write(out.resolve(FOLDER).resolve(result.room().id() + ".schem"), bytes);
            ExtractRooms.report(result, bytes.length);
            (f1 ? floorOne : masterSeven).add(result);
        }
        Files.writeString(out.resolve("hypixel_f1.json"), ExtractRooms.json(floorOne, String.format(SOURCE, "Floor 1")), StandardCharsets.UTF_8);
        Files.writeString(out.resolve("hypixel_m7.json"), ExtractRooms.json(masterSeven, String.format(SOURCE, "Master Mode Floor 7")), StandardCharsets.UTF_8);
        patchM7(out, catalogue, replaced);
        DoorPieces.write(runs, out.toAbsolutePath().getParent().resolve("door_pieces.json"));
    }

    private static String chosenLabel(List<Seen> cluster) {
        Seen chosen = choose(cluster);
        List<String> all = cluster.stream().map(seen -> seen.run().id()).toList();
        return chosen.run().id() + " " + chosen.cells()[0][0] + "," + chosen.cells()[0][1] + " (seen in " + all + ")";
    }

    static Run load(Path capture, RoomCatalogue catalogue) throws IOException {
        String id = capture.getFileName().toString().replaceFirst("_\\d{4}-\\d{2}-\\d{2}.*$", "");
        AnvilWorld world = new AnvilWorld(capture.resolve("worlds").resolve("world_002").resolve("region"));
        Run run = new Run(id, id.startsWith("f1"), world, new ArrayList<>(), new ArrayList<>(), placedBlocks(capture),
                CaptureMobs.read(capture), entry(capture));
        detectRooms(run, catalogue);
        detectDoors(run);
        System.out.println(id + ": " + run.rooms().size() + " rooms, " + run.doors().size() + " doors, " + run.mobs().size() + " mobs");
        return run;
    }

    static void detectRooms(Run run, RoomCatalogue catalogue) {
        List<int[]> unknown = new ArrayList<>();
        for (int gz = 0; gz < GRID; gz++) {
            for (int gx = 0; gx < GRID; gx++) {
                if (run.roomAt(gx, gz) != null) continue;
                int cx = RoomCatalogue.centre(gx), cz = RoomCatalogue.centre(gz);
                if (RoomCatalogue.topLayer(run.world()::block, cx, cz) == 0) continue;
                RoomCatalogue.Found found = catalogue.identify(run.world()::block, cx, cz);
                if (found == null || found.rotation() == null) {
                    unknown.add(new int[]{gx, gz});
                    continue;
                }
                List<int[]> cells = new ArrayList<>();
                for (int[] centre : found.centres()) {
                    cells.add(new int[]{(centre[0] - RoomCatalogue.CENTRE_START) / 32, (centre[1] - RoomCatalogue.CENTRE_START) / 32});
                }
                run.rooms().add(new Seen(run, sorted(cells), found));
            }
        }
        for (int[] cell : unknown) {
            Seen owner = null;
            for (int[] step : new int[][]{{1, 0}, {-1, 0}, {0, 1}, {0, -1}}) {
                Seen next = run.roomAt(cell[0] + step[0], cell[1] + step[1]);
                if (next == null || next.cells().length >= SHAPE_CELLS.get(next.found().entry().shape())) continue;
                if (owner != null && owner != next) throw new IllegalStateException(run.id() + " cell " + cell[0] + "," + cell[1] + " could belong to two rooms");
                owner = next;
            }
            if (owner == null) {
                System.out.println(run.id() + " cell " + cell[0] + "," + cell[1] + " is not a catalogue room, left out (the boss arena reaches into the grid on small floors)");
                continue;
            }
            List<int[]> cells = new ArrayList<>(List.of(owner.cells()));
            cells.add(cell);
            run.rooms().set(run.rooms().indexOf(owner), new Seen(run, sorted(cells), owner.found()));
            System.out.println(run.id() + " cell " + cell[0] + "," + cell[1] + " joins " + owner.name() + " (its centre column does not match the catalogue)");
        }
        for (Seen room : run.rooms()) {
            int expected = SHAPE_CELLS.get(room.found().entry().shape());
            if (room.cells().length != expected) {
                throw new IllegalStateException(run.id() + " " + room.name() + " covers " + room.cells().length + " cells, its shape needs " + expected);
            }
        }
    }

    private static int[][] sorted(List<int[]> cells) {
        return cells.stream().sorted(Comparator.<int[]>comparingInt(cell -> cell[1]).thenComparingInt(cell -> cell[0])).toArray(int[][]::new);
    }

    static void detectDoors(Run run) {
        for (int gz = 0; gz < GRID; gz++) {
            for (int gx = 0; gx < GRID; gx++) {
                for (int[] step : new int[][]{{1, 0}, {0, 1}}) {
                    Seen own = run.roomAt(gx, gz), other = run.roomAt(gx + step[0], gz + step[1]);
                    if (own == null || other == null || own == other) continue;
                    if (open(run.world(), gx, gz, step[0] == 1)) run.doors().add(new int[][]{{gx, gz}, {gx + step[0], gz + step[1]}});
                }
            }
        }
    }

    private static boolean open(AnvilWorld world, int gx, int gz, boolean eastWest) {
        for (int across = -1; across <= 1; across++) {
            int x = eastWest ? ORIGIN + 32 * gx + 31 + across : ORIGIN + 32 * gx + ExtractRooms.CENTRE;
            int z = eastWest ? ORIGIN + 32 * gz + ExtractRooms.CENTRE : ORIGIN + 32 * gz + 31 + across;
            for (int y = ExtractRooms.DOOR_BOTTOM_Y; y <= ExtractRooms.DOOR_TOP_Y; y++) {
                String state = world.block(x, y, z);
                if (!BlockStates.passable(state) && !DOOR_BLOCKS.contains(AnvilWorld.bare(state))) return false;
            }
        }
        return true;
    }

    @SuppressWarnings("unchecked")
    private static double[] entry(Path capture) throws IOException {
        Map<String, Object> session = (Map<String, Object>) Json.parse(Files.readString(capture.resolve("session.json")));
        for (Object raw : (List<Object>) session.get("worlds")) {
            Map<String, Object> world = (Map<String, Object>) raw;
            if (!"world_002".equals(world.get("id"))) continue;
            Map<String, Object> at = (Map<String, Object>) world.get("entryPosition");
            return new double[]{(Double) at.get("x"), (Double) at.get("y"), (Double) at.get("z")};
        }
        return null;
    }

    /** The sighting a room is cut from: a Floor 1 run first, then the one whose mobs were seen best. */
    static Seen choose(List<Seen> cluster) {
        Seen best = null;
        double bestScore = -1;
        for (Seen seen : cluster) {
            double score = (seen.run().floorOne() ? 1_000_000 : 0) + (seen.blind() ? 0 : 1000) + seen.mobs().size()
                    + (annexMinZ(seen) != RoomSource.NO_ANNEX ? 100_000 : 0);
            if (score > bestScore) {
                bestScore = score;
                best = seen;
            }
        }
        return best;
    }

    static RoomSource.Room room(Seen seen, List<Seen> cluster, RoomCatalogue catalogue, Map<String, Double> starRatio) {
        RoomCatalogue.Entry entry = seen.found().entry();
        String kind = entry.type().equals("CHAMPION") ? "MINIBOSS" : entry.type();
        String name = WIKI_NAMES.getOrDefault(entry.name(), entry.name().replaceAll("-\\d+$", "").replace('-', ' ').replace(" Room", ""));
        String id = IDS.getOrDefault(entry.name(), name.toLowerCase(Locale.ROOT).replaceAll("[^a-z0-9]+", "_").replaceAll("^_|_$", ""));
        if (kind.equals("MINIBOSS") && !id.startsWith("miniboss_")) id = "miniboss_" + id;
        List<RoomSource.Secret> secrets = new ArrayList<>();
        List<RoomSource.Extra> extras = new ArrayList<>();
        Set<String> seenPoints = new HashSet<>();
        for (RoomCatalogue.Point point : catalogue.points(entry.name())) {
            int[] at = seen.found().toWorld(point.x(), point.z());
            if (!seenPoints.add(point.category() + at[0] + "," + point.y() + "," + at[1])) continue;
            String type = CATEGORY_TYPES.get(point.category());
            if (type != null) {
                double offset = type.equals("ITEM") || type.equals("BAT") ? 0.5 : 0;
                secrets.add(new RoomSource.Secret(type, type, at[0] + offset, point.y(), at[1] + offset, true, false, point.name()));
            } else if (EXTRA_KINDS.containsKey(point.category())) {
                extras.add(new RoomSource.Extra(EXTRA_KINDS.get(point.category()), point.name(), at[0], point.y(), at[1]));
            }
        }
        double[] spawnPoint = kind.equals("ENTRANCE") ? entrySpawn(seen, cluster) : null;
        String tag = seen.run().floorOne() ? "hypixel_f1" : "hypixel_m7";
        return new RoomSource.Room(id, name, kind, seen.cells(), 0, 255, secrets, spawns(seen, starRatio), List.of(), entry.crypts(),
                extras, seen.run().placed(), spawnPoint, annexMinZ(seen), FOLDER, tag, entry.name(), 0);
    }

    private static List<RoomSource.Spawn> spawns(Seen seen, Map<String, Double> starRatio) {
        boolean blind = seen.blind();
        List<RoomSource.Spawn> spawns = new ArrayList<>();
        for (CaptureMobs.Mob mob : seen.mobs()) {
            boolean guessed = blind && !MINIBOSSES.contains(mob.mobId());
            boolean starred = guessed ? starRatio.getOrDefault(mob.mobId(), 0.0) >= 0.5 : mob.starred();
            String seenAs = mob.mobId().equals(CaptureMobs.FLOOR_ONE_IDS.get(mob.seenAs()))
                    && mob.seenAs().toUpperCase(Locale.ROOT).replace(' ', '_').equals(mob.mobId()) ? null : mob.seenAs();
            spawns.add(new RoomSource.Spawn(mob.mobId(), mob.x(), mob.y(), mob.z(), starred, guessed, seenAs));
        }
        return spawns;
    }

    /** How often each Floor 1 mob was starred where stars were visible; Floor 1 runs decide where they saw the mob. */
    static Map<String, Double> starRatios(List<Run> runs) {
        Map<String, int[]> floorOne = new HashMap<>(), all = new HashMap<>();
        for (Run run : runs) {
            for (Seen seen : run.rooms()) {
                if (seen.blind()) continue;
                for (CaptureMobs.Mob mob : seen.mobs()) {
                    if (MINIBOSSES.contains(mob.mobId())) continue;
                    for (Map<String, int[]> counts : run.floorOne() ? List.of(floorOne, all) : List.of(all)) {
                        int[] count = counts.computeIfAbsent(mob.mobId(), ignored -> new int[2]);
                        count[0]++;
                        if (mob.starred()) count[1]++;
                    }
                }
            }
        }
        Map<String, Double> ratios = new HashMap<>();
        all.forEach((mob, count) -> ratios.put(mob, count[1] / (double) count[0]));
        floorOne.forEach((mob, count) -> ratios.put(mob, count[1] / (double) count[0]));
        System.out.println("star ratios " + new java.util.TreeMap<>(ratios));
        return ratios;
    }

    /** The entrance's spawn: the run's entry point where it lies in this entrance, carried over from another sighting otherwise. */
    private static double[] entrySpawn(Seen seen, List<Seen> cluster) {
        for (Seen other : cluster) {
            double[] entry = other.run().entry();
            if (entry == null) continue;
            int gx = Math.floorDiv((int) Math.floor(entry[0]) - ORIGIN, 32), gz = Math.floorDiv((int) Math.floor(entry[2]) - ORIGIN, 32);
            if (other.cells()[0][0] != gx || other.cells()[0][1] != gz) continue;
            double[] relative = toRelative(other.found(), entry[0], entry[2]);
            double[] local = toLocal(seen.found(), relative[0], relative[1]);
            return new double[]{local[0] + ORIGIN, entry[1], local[1] + ORIGIN};
        }
        int[] cell = seen.cells()[0];
        return new double[]{ORIGIN + 32 * cell[0] + ExtractRooms.CENTRE + 0.5, ExtractRooms.DOOR_BOTTOM_Y + 6, ORIGIN + 32 * cell[1] + ExtractRooms.CENTRE + 0.5};
    }

    /** The spawn cave some entrances keep outside the grid: the blocks north of an entrance on the grid's top row. */
    static int annexMinZ(Seen seen) {
        if (!seen.found().entry().type().equals("ENTRANCE") || seen.cells()[0][1] != 0) return RoomSource.NO_ANNEX;
        int x0 = ORIGIN + 32 * seen.cells()[0][0];
        int lowest = RoomSource.NO_ANNEX;
        for (int z = ORIGIN - 1; z >= ORIGIN - 24; z--) {
            boolean any = false;
            for (int x = x0; x < x0 + ExtractRooms.ROOM && !any; x++) {
                for (int y = 0; y < 256 && !any; y++) any = !AnvilWorld.isAir(seen.run().world().block(x, y, z));
            }
            if (any) lowest = z;
        }
        return lowest;
    }

    /** The run's grid, with every door any sighting of this room had added to the room's own cells. */
    static RoomSource.Grid grid(Seen chosen, List<Seen> cluster) {
        List<int[][]> doors = new ArrayList<>(chosen.run().doors());
        Set<String> known = new HashSet<>();
        for (int[][] door : doors) known.add(doorKey(door));
        for (Seen seen : cluster) {
            if (seen == chosen) continue;
            for (int[][] door : seen.run().doors()) {
                boolean a = contains(seen.cells(), door[0]), b = contains(seen.cells(), door[1]);
                if (a == b) continue;
                boolean eastWest = door[0][1] == door[1][1];
                int low = eastWest ? Math.min(door[0][0], door[1][0]) : Math.min(door[0][1], door[1][1]);
                int sx = eastWest ? ORIGIN + 32 * low + 31 : ORIGIN + 32 * door[0][0] + ExtractRooms.CENTRE;
                int sz = eastWest ? ORIGIN + 32 * door[0][1] + ExtractRooms.CENTRE : ORIGIN + 32 * low + 31;
                double[] relative = toRelative(seen.found(), sx, sz);
                double[] local = toLocal(chosen.found(), relative[0], relative[1]);
                int dx = (int) Math.round(local[0]), dz = (int) Math.round(local[1]);
                int[][] moved;
                if (Math.floorMod(dx, 32) == 31) {
                    moved = new int[][]{{Math.floorDiv(dx, 32), Math.floorDiv(dz, 32)}, {Math.floorDiv(dx, 32) + 1, Math.floorDiv(dz, 32)}};
                } else if (Math.floorMod(dz, 32) == 31) {
                    moved = new int[][]{{Math.floorDiv(dx, 32), Math.floorDiv(dz, 32)}, {Math.floorDiv(dx, 32), Math.floorDiv(dz, 32) + 1}};
                } else {
                    throw new IllegalStateException(seen.name() + " door " + sx + "," + sz + " lands off a seam in " + chosen.run().id());
                }
                if (contains(chosen.cells(), moved[0]) == contains(chosen.cells(), moved[1])) {
                    throw new IllegalStateException(seen.name() + " door from " + seen.run().id() + " does not touch the room in " + chosen.run().id());
                }
                if (known.add(doorKey(moved))) doors.add(moved);
            }
        }
        return new RoomSource.Grid(ORIGIN, ORIGIN, 1, doors.toArray(int[][][]::new));
    }

    static String doorKey(int[][] door) {
        int[] a = door[0], b = door[1];
        if (a[0] > b[0] || (a[0] == b[0] && a[1] > b[1])) {
            int[] swap = a;
            a = b;
            b = swap;
        }
        return a[0] + "," + a[1] + "-" + b[0] + "," + b[1];
    }

    private static boolean contains(int[][] cells, int[] cell) {
        for (int[] own : cells) if (own[0] == cell[0] && own[1] == cell[1]) return true;
        return false;
    }

    private static int[] validTurns(RoomSource.Room room) {
        int cells = room.cells().length;
        int xs = (int) java.util.Arrays.stream(room.cells()).mapToInt(cell -> cell[0]).distinct().count();
        int zs = (int) java.util.Arrays.stream(room.cells()).mapToInt(cell -> cell[1]).distinct().count();
        if (room.annexMinZ() != RoomSource.NO_ANNEX) return new int[]{0};
        if (cells == 1 || (cells == 4 && xs == 2 && zs == 2)) return new int[]{0, 1, 2, 3};
        if (xs == 1 || zs == 1) return new int[]{0, 2};
        return new int[]{0};
    }

    /** The share of non-air blocks in which two sightings of a room differ, compared in the catalogue's room frame. */
    static double difference(Seen first, Seen second) {
        int same = 0, differ = 0;
        for (int[] cell : first.cells()) {
            int x0 = ORIGIN + 32 * cell[0], z0 = ORIGIN + 32 * cell[1];
            for (int x = x0; x < x0 + ExtractRooms.ROOM; x++) {
                for (int z = z0; z < z0 + ExtractRooms.ROOM; z++) {
                    double[] relative = toRelative(first.found(), x, z);
                    double[] local = toLocal(second.found(), relative[0], relative[1]);
                    int ox = (int) Math.round(local[0]) + ORIGIN, oz = (int) Math.round(local[1]) + ORIGIN;
                    for (int y = 0; y < 200; y++) {
                        String a = AnvilWorld.bare(first.run().world().block(x, y, z));
                        String b = AnvilWorld.bare(second.run().world().block(ox, y, oz));
                        if (a.equals(AnvilWorld.AIR) && b.equals(AnvilWorld.AIR)) continue;
                        if (a.equals(b)) same++;
                        else differ++;
                    }
                }
            }
        }
        return differ / (double) Math.max(1, same + differ);
    }

    /** The share of non-air blocks inside the footprint in which a cut room differs from the template it may replace. */
    static double gap(ExtractRooms.Result result, Reference reference) {
        int same = 0, differ = 0;
        int width = 0, depth = 0;
        for (int[] cell : ExtractRooms.SHAPES.get(result.shape())) {
            width = Math.max(width, (cell[0] + 1) * ExtractRooms.PITCH - 1);
            depth = Math.max(depth, (cell[1] + 1) * ExtractRooms.PITCH - 1);
        }
        int yLo = Math.min(result.structureY(), reference.structureY()) + ExtractRooms.FLOOR_Y;
        int yHi = yLo + 160;
        for (int x = 0; x < width; x++) {
            for (int z = 0; z < depth; z++) {
                for (int y = yLo; y <= yHi; y++) {
                    String a = AnvilWorld.bare(result.box().get(x - result.structureX(), y, z - result.structureZ()));
                    String b = AnvilWorld.bare(reference.blocks().block(x, y, z));
                    if (a.equals(AnvilWorld.AIR) && b.equals(AnvilWorld.AIR)) continue;
                    if (a.equals(b)) same++;
                    else differ++;
                }
            }
        }
        return differ / (double) Math.max(1, same + differ);
    }

    private static ExtractRooms.Result rename(ExtractRooms.Result result, String id) {
        if (result.room().id().equals(id)) return result;
        return new ExtractRooms.Result(result.room().withId(id), result.shape(), result.structureX(), result.structureY(), result.structureZ(),
                result.box(), result.anchors(), result.sockets(), result.spawns(), result.crypts(), result.extras(), result.stand(),
                result.secretCount(), result.turns(), result.notes());
    }

    /** Every template the captures may replace, read from whichever room file defines it now. */
    static Map<String, Reference> references(Path out) throws IOException {
        Map<String, Reference> references = new HashMap<>();
        Pattern template = Pattern.compile("\n      \"id\": \"(\\w+)\",[\\s\\S]*?\"file\": \"([\\w/]+\\.schem)\", \"x\": (-?\\d+), \"y\": (-?\\d+), \"z\": (-?\\d+)");
        for (String file : List.of("m7.json", "hypixel_f1.json", "hypixel_m7.json")) {
            Path path = out.resolve(file);
            if (!Files.exists(path)) continue;
            Matcher matcher = template.matcher(Files.readString(path));
            while (matcher.find()) {
                String id = matcher.group(1);
                if (!M7_IDS.containsValue(id) || references.containsKey(id)) continue;
                int x = Integer.parseInt(matcher.group(3)), y = Integer.parseInt(matcher.group(4)), z = Integer.parseInt(matcher.group(5));
                references.put(id, new Reference(id, SchemBlocks.read(out.resolve(matcher.group(2)), x, ExtractRooms.FLOOR_Y + y, z), x, y, z));
            }
        }
        return references;
    }

    @SuppressWarnings("unchecked")
    static Map<String, String> placedBlocks(Path capture) throws IOException {
        Map<String, String> placed = new HashMap<>();
        for (String line : Files.readAllLines(capture.resolve("streams").resolve("blocks.jsonl"), StandardCharsets.UTF_8)) {
            if (!line.contains("\"world_002\"") || !(line.contains("chest") || line.contains("lever"))) continue;
            Map<String, Object> event = (Map<String, Object>) Json.parse(line);
            Map<String, Object> data = (Map<String, Object>) event.get("data");
            if (event.get("type").equals("block:update")) {
                Map<String, Object> pos = (Map<String, Object>) data.get("pos");
                place(placed, ((Double) pos.get("x")).intValue(), ((Double) pos.get("y")).intValue(), ((Double) pos.get("z")).intValue(),
                        (String) data.get("blockState"));
            } else if (event.get("type").equals("block:section")) {
                Map<String, Object> section = (Map<String, Object>) data.get("sectionPos");
                int sx = ((Double) section.get("x")).intValue() * 16, sy = ((Double) section.get("y")).intValue() * 16,
                        sz = ((Double) section.get("z")).intValue() * 16;
                List<Object> positions = (List<Object>) data.get("positions");
                List<Object> states = (List<Object>) data.get("states");
                for (int i = 0; i < positions.size(); i++) {
                    int packed = ((Double) positions.get(i)).intValue();
                    place(placed, sx + ((packed >> 8) & 15), sy + (packed & 15), sz + ((packed >> 4) & 15), (String) states.get(i));
                }
            }
        }
        return placed;
    }

    private static void place(Map<String, String> placed, int x, int y, int z, String blockState) {
        String state = blockState.replaceFirst("^Block\\{([^}]*)}", "$1");
        if (!PLACED_BLOCKS.contains(AnvilWorld.bare(state))) return;
        if (state.contains("powered=true")) state = state.replace("powered=true", "powered=false");
        placed.putIfAbsent(x + "," + y + "," + z, state);
    }

    /** The catalogue frame of every M7 template, found by reading its schematic as if pasted on cell (0,0). */
    static Map<String, RoomCatalogue.Found> m7Rooms(RoomCatalogue catalogue, Path out) throws IOException {
        Map<String, RoomCatalogue.Found> found = new LinkedHashMap<>();
        String json = Files.readString(out.resolve("m7.json"));
        Matcher template = Pattern.compile("\"id\": \"(\\w+)\",\\s*\"name[\\s\\S]*?\"file\": \"([\\w/]+\\.schem)\", \"x\": (-?\\d+), \"y\": (-?\\d+), \"z\": (-?\\d+)").matcher(json);
        while (template.find()) {
            SchemBlocks blocks = SchemBlocks.read(out.resolve(template.group(2)), ORIGIN + Integer.parseInt(template.group(3)),
                    ExtractRooms.FLOOR_Y + Integer.parseInt(template.group(4)), ORIGIN + Integer.parseInt(template.group(5)));
            RoomCatalogue.Found room = catalogue.identify(blocks::block, RoomCatalogue.centre(0), RoomCatalogue.centre(0));
            if (room != null && room.rotation() != null) found.put(template.group(1), room);
        }
        return found;
    }

    /**
     * Drops the practice-map templates a captured room replaced (and their schematics), and gives the rest the
     * catalogue's name, route points, secret labels and crypt count.
     */
    static void patchM7(Path out, RoomCatalogue catalogue, Set<String> replaced) throws IOException {
        Path file = out.resolve("m7.json");
        String json = Files.readString(file);
        for (String id : replaced) {
            int start = json.indexOf("    {\n      \"id\": \"" + id + "\"");
            if (start < 0) continue;
            int end = json.indexOf("\n    }", start) + 6;
            if (json.startsWith(",\n", end)) end += 2;
            else if (json.substring(0, start).endsWith(",\n")) start -= 2;
            json = json.substring(0, start) + json.substring(end);
            Files.deleteIfExists(out.resolve("m7").resolve(id + ".schem"));
            System.out.println("m7.json: " + id + " is replaced by its captured room");
        }
        if (!json.endsWith("\n  ]\n}\n")) json = json.replaceFirst("\\s*]\\s*}\\s*$", "\n  ]\n}\n");
        Files.writeString(file, json, StandardCharsets.UTF_8);
        Map<String, RoomCatalogue.Found> m7 = m7Rooms(catalogue, out);
        for (Map.Entry<String, RoomCatalogue.Found> entry : m7.entrySet()) {
            RoomCatalogue.Found frame = entry.getValue();
            String name = frame.entry().name();
            int start = json.indexOf("\"id\": \"" + entry.getKey() + "\"");
            int end = json.indexOf("\n    }", start);
            String body = json.substring(start, end);
            body = body.replaceFirst("      \"catalogueName\": \"[^\"]*\",\n", "");
            body = body.replaceFirst("(\"kind\": \"\\w+\",\n)", "$1      \"catalogueName\": \"" + name + "\",\n");
            body = labelAnchors(body, frame, catalogue.points(name));
            List<RoomSource.Extra> extras = new ArrayList<>();
            for (RoomCatalogue.Point point : catalogue.points(name)) {
                if (!EXTRA_KINDS.containsKey(point.category())) continue;
                double[] local = toLocal(frame, point.x(), point.z());
                extras.add(new RoomSource.Extra(EXTRA_KINDS.get(point.category()), point.name(), (int) local[0], point.y(), (int) local[1]));
            }
            body = trimCrypts(body, frame.entry().crypts());
            body = body.replaceFirst(",\n      \"secretExtras\": \\[[^\\]]*]", "");
            if (!extras.isEmpty()) body = body + ",\n      \"secretExtras\": [" + ExtractRooms.extrasJson(extras) + "]";
            json = json.substring(0, start) + body + json.substring(end);
        }
        Files.writeString(file, json, StandardCharsets.UTF_8);
    }

    /** Names each practice-map secret after the catalogue secret of its kind within two blocks of it. */
    private static String labelAnchors(String body, RoomCatalogue.Found frame, List<RoomCatalogue.Point> points) {
        Matcher anchor = Pattern.compile("\\{\"type\": \"(\\w+)\", \"x\": (-?\\d+), \"y\": (-?\\d+), \"z\": (-?\\d+), \"variant\": \"\\w+\"(, \"label\": \"[^\"]*\")?").matcher(body);
        StringBuilder out = new StringBuilder();
        while (anchor.find()) {
            String type = anchor.group(1);
            int x = Integer.parseInt(anchor.group(2)), y = Integer.parseInt(anchor.group(3)) + ExtractRooms.FLOOR_Y, z = Integer.parseInt(anchor.group(4));
            String label = null;
            double best = 2.5;
            for (RoomCatalogue.Point point : points) {
                if (!type.equals(CATEGORY_TYPES.get(point.category()))) continue;
                double[] local = toLocal(frame, point.x(), point.z());
                double distance = Math.sqrt(Math.pow(local[0] - x, 2) + Math.pow(point.y() - y, 2) + Math.pow(local[1] - z, 2));
                if (distance < best) {
                    best = distance;
                    label = point.name();
                }
            }
            String plain = anchor.group().replaceFirst(", \"label\": \"[^\"]*\"$", "");
            anchor.appendReplacement(out, Matcher.quoteReplacement(label == null ? plain : plain + ", \"label\": \"" + label + "\""));
        }
        anchor.appendTail(out);
        return out.toString();
    }

    static double[] toRelative(RoomCatalogue.Found found, double x, double z) {
        double dx = x - found.cornerX(), dz = z - found.cornerZ();
        return switch (found.rotation()) {
            case "W" -> new double[]{dz, -dx};
            case "N" -> new double[]{-dx, -dz};
            case "E" -> new double[]{-dz, dx};
            default -> new double[]{dx, dz};
        };
    }

    static double[] toLocal(RoomCatalogue.Found frame, double x, double z) {
        double cx = frame.cornerX(), cz = frame.cornerZ();
        double[] world = switch (frame.rotation()) {
            case "W" -> new double[]{cx - z, cz + x};
            case "N" -> new double[]{cx - x, cz - z};
            case "E" -> new double[]{cx + z, cz - x};
            default -> new double[]{cx + x, cz + z};
        };
        return new double[]{world[0] - ORIGIN, world[1] - ORIGIN};
    }

    private static String trimCrypts(String body, int target) {
        int open = body.indexOf("\"crypts\": [") + 11;
        int close = matching(body, open - 1);
        List<String> crypts = new ArrayList<>();
        Matcher crypt = Pattern.compile("\\{[^}]*}").matcher(body.substring(open, close));
        while (crypt.find()) crypts.add(crypt.group());
        if (crypts.size() <= target) return body;
        StringBuilder items = new StringBuilder();
        ExtractRooms.joinLines(items, crypts.subList(0, target));
        return body.substring(0, open) + items + body.substring(close);
    }

    private static int matching(String text, int open) {
        int depth = 0;
        for (int i = open; i < text.length(); i++) {
            if (text.charAt(i) == '[') depth++;
            if (text.charAt(i) == ']' && --depth == 0) return i;
        }
        throw new IllegalStateException("unbalanced array");
    }

    /** A Sponge schematic read back for the catalogue's room detection. */
    record SchemBlocks(int width, int height, int length, int x0, int y0, int z0, String[] states) {
        static SchemBlocks read(Path file, int x0, int y0, int z0) throws IOException {
            Nbt.Tag root = Nbt.read(new GZIPInputStream(new ByteArrayInputStream(Files.readAllBytes(file))));
            int width = root.get("Width").intValue(), height = root.get("Height").intValue(), length = root.get("Length").intValue();
            Map<Integer, String> palette = new HashMap<>();
            root.get("Palette").compound().forEach((state, id) -> palette.put(id.intValue(), state));
            byte[] data = (byte[]) root.get("BlockData").value();
            String[] states = new String[width * height * length];
            int index = 0, at = 0;
            while (at < data.length) {
                int value = 0, shift = 0, b;
                do {
                    b = data[at++];
                    value |= (b & 0x7F) << shift;
                    shift += 7;
                } while ((b & 0x80) != 0);
                states[index++] = palette.get(value);
            }
            return new SchemBlocks(width, height, length, x0, y0, z0, states);
        }

        String block(int x, int y, int z) {
            int bx = x - x0, by = y - y0, bz = z - z0;
            if (bx < 0 || by < 0 || bz < 0 || bx >= width || by >= height || bz >= length) return AnvilWorld.AIR;
            return states[bx + bz * width + by * width * length];
        }
    }
